async (page) => {
  const checks=[],failures=[];
  const check=(ok,name)=>{(ok?checks:failures).push(name);};
  await page.keyboard.press('Control+0');await page.setViewportSize({width:1440,height:900});
  await page.goto('http://127.0.0.1:5088/?mode=fixed');
  check(await page.locator('.lab-sidebar .ui-icon').evaluateAll(nodes=>nodes.every(node=>{const b=node.getBoundingClientRect();return b.width<=30&&b.height<=30;})),'shared analytical icons remain UI-sized');
  check(!(await page.locator('.vision-tag').textContent()).includes('Lab04'),'analytical badge retains Lab03 identity');
  await page.goto('http://127.0.0.1:5088/simulation');
  check(await page.locator('#circuit-svg').evaluate(svg=>{const resistor=svg.querySelector('#emitter-resistor'),lead=svg.querySelector('#emitter-ground-lead');if(!resistor||!lead)return false;const a=resistor.getPointAtLength(resistor.getTotalLength()),b=lead.getPointAtLength(0);return Math.hypot(a.x-b.x,a.y-b.y)<.01;}),'emitter resistor reaches ground lead with no electrical gap');
  await page.locator('#spice-r1').fill('1000000000');
  check(!(await page.evaluate(()=>LabDashboard.validate())).valid,'Validate rejects converted resistor values above engine bounds');
  await page.locator('#spice-r1').fill('1e999');check(!(await page.evaluate(()=>LabDashboard.validate())).valid,'Validate rejects conversion overflow');
  await page.locator('#spice-r1').fill('1e-999');check(!(await page.evaluate(()=>LabDashboard.validate())).valid,'Validate rejects conversion underflow');
  await page.locator('#reset-lab').click();
  let release;const gate=new Promise(resolve=>release=resolve);
  const hold=async route=>{if(route.request().method()==='POST')await gate;await route.continue();};
  await page.route('**/simulation',hold);
  await page.getByRole('button',{name:'Run Simulation',exact:true}).click();
  await page.locator('#spice-re').fill('nan');release();
  await page.waitForFunction(()=>!document.querySelector('#spice-form').hasAttribute('aria-busy'));
  await page.unroute('**/simulation',hold);
  check(!(await page.locator('#spice-status').getAttribute('class')).includes('status-ok'),'pending input edit cannot produce a current success banner');
  check((await page.locator('.run-state').allTextContents()).every(text=>text.startsWith('Stale')),'pending edit retains only explicitly stale historical runs');
  await page.locator('#reset-lab').click();
  await page.locator('#overlay-dc').uncheck();await page.locator('#overlay-ac').uncheck();
  await page.getByRole('button',{name:'Run Simulation',exact:true}).click();await page.waitForFunction(()=>!document.querySelector('#spice-form').hasAttribute('aria-busy'));
  check(await page.locator('.dc-layer').evaluate(node=>getComputedStyle(node).display)==='none','DC switch remains off across redraw');
  check(await page.locator('.ac-layer').evaluate(node=>getComputedStyle(node).display)==='none','AC switch remains off across redraw');
  await page.locator('#spice-re').fill('2');await page.locator('#spice-amplitude').fill('20');await page.locator('#spice-frequency').fill('2000');await page.locator('#analysis').selectOption('dc');
  await Promise.all([page.waitForNavigation(),page.locator('#spice-form').evaluate(form=>form.submit())]);
  check(await page.locator('#spice-re').inputValue()==='2','native POST reproducer contains submitted current values');
  await page.locator('#reset-lab').click();
  check(await page.locator('#spice-re').inputValue()==='1','POST-origin Reset restores canonical RE');
  check(await page.locator('#spice-amplitude').inputValue()==='10','POST-origin Reset restores canonical amplitude');
  check(await page.locator('#spice-frequency').inputValue()==='1000','POST-origin Reset restores canonical frequency');
  const report={passed:checks.length,checks,failures};
  await page.evaluate(report=>window.labReviewVerification=report,report);
  if(failures.length)throw new Error(JSON.stringify(report));
  return report;
}
